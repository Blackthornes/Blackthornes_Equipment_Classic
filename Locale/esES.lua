-- Blackthornes Equipment -- Locale/esES.lua
-- Spanish: the words players see, on a Spanish client (Spain or Latin America).
--
-- Each line is the English key (exactly as the code writes it) and its
-- Spanish. A key with no line here shows in English. The Spanish speaks to
-- the player as "tú", so it reads well in Spain and Latin America alike,
-- and uses the game's words (equipo, mejora, misión, vendedor, instructor,
-- nivel, zona, casa de subastas, estadísticas, pesos, habilidad, metros).
-- A line may name its values by place ("%2$s ... %1$s") where Spanish word
-- order needs it; L.Format puts them in order.
--
-- Item, NPC, quest, zone and skill names stay as the data or the client gives
-- them. tools/check_locale.py lists keys with no line here and lines no
-- longer used.

