"""Writes Data/NameIDs.lua: the creature and item IDs behind the English
names Equipment's data uses, so a client in another language can show the
game's own name for each (Logic/Names.lua).

Run from the repository root after the other data tools, with the
mangoszero world database checked out somewhere:

    python tools/make_name_ids.py <mangoszero database>

  github.com/mangoszero/database   World/Setup/FullDB: creature_template
                                   and item_template (entry and name)

Only names that Equipment's own data files show are kept: quest givers,
who takes a quest back, the mobs and bosses a step names, vendors and
trainers, the mobs that drop a recipe, and the items a step asks for. A name more than one creature
carries keeps the lowest entry; the game gives every one the same name.
Objects are left out: the client has no way to name one by its ID.
"""

import sys
from pathlib import Path

from lupa import lua51

sys.path.insert(0, str(Path(__file__).resolve().parent))
from make_sources import rows  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent

DATA_FILES = ["Data/Sources.lua", "Data/QuestEnds.lua", "Data/QuestStarts.lua",
              "Data/DungeonQuests.lua", "Data/WeaponTrainers.lua", "Data/Crafts.lua"]


def load_data():
    lua = lua51.LuaRuntime(unpack_returned_tuples=True)
    lua.execute("ns = { NewModule = function(name) local m = {} ns[name] = m return m end }")
    for name in DATA_FILES:
        chunk = lua.eval("function(src, name) return loadstring(src, name) end")(
            (ROOT / name).read_text(encoding="utf-8"), name)
        chunk("Blackthornes_Equipment", lua.eval("ns"))
    return lua.eval("ns")


def values(table):
    return [table[k] for k in table] if table is not None else []


def wanted_names(ns):
    """The creature names and item names the data shows."""
    npcs, items = set(), set()
    S = ns.Sources

    def add(kind, name, item=None):
        if not isinstance(name, str) or not name:
            return
        if kind in ("npc", "mob", "boss", "vendor"):
            npcs.add(name)
        if isinstance(item, str) and item:
            items.add(item)

    for quest in values(S.QUESTS):
        add("npc", quest[6])
    for npc in values(S.NPCS):
        add("npc", npc[1])
    for boss in values(S.BOSSES):
        add("boss", boss[1])
    for row in values(S.ENDS):
        add(row[1], row[2])
        for part in [row.o] + values(row.m):
            if part is not None:
                add(part[1], part[2], part[6])
    for row in values(S.STARTS):
        if isinstance(row[2], str):
            items.add(row[2])
        for index in range(4, len(values(row)) + 1):
            part = row[index]
            if part is not None and not isinstance(part, (int, float, str)):
                add(part[1], part[2])
    for quest in values(ns.DUNGEON_QUESTS):
        add("npc", quest[7])
    crafts = ns.Crafts
    if crafts is not None:
        for npc in values(crafts.NPCS):
            add("npc", npc[1])
        for recipe in values(crafts.RECIPES):
            for name in values(recipe.n):
                add("mob", name)
    trainers = ns.WeaponTrainers and ns.WeaponTrainers.TRAINERS
    for side in values(trainers):
        for trainer in values(side):
            add("npc", trainer.name)
    return npcs, items


def ids_by_name(path, table, id_column, name_column, wanted):
    found = {}
    for row in rows(path, table):
        name = row[name_column]
        if name in wanted:
            entry = int(row[id_column])
            if name not in found or entry < found[name]:
                found[name] = entry
    return found


def lua_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def write(npcs, items):
    out = [
        "-- Blackthornes Equipment -- Data/NameIDs.lua",
        "-- The creature and item IDs behind the English names the data shows,",
        "-- so a client in another language can show the game's own name",
        "-- (Logic/Names.lua). Generated by tools/make_name_ids.py from Classic",
        "-- 1.12 data; never typed by hand.",
        "",
        "local _, ns = ...",
        "",
        "ns.NAME_IDS = {",
        "    npc = {",
    ]
    for name in sorted(npcs):
        out.append(f"        [{lua_string(name)}] = {npcs[name]},")
    out.append("    },")
    out.append("    item = {")
    for name in sorted(items):
        out.append(f"        [{lua_string(name)}] = {items[name]},")
    out.append("    },")
    out.append("}")
    (ROOT / "Data" / "NameIDs.lua").write_text("\n".join(out) + "\n", encoding="utf-8")


def main(argv):
    if len(argv) != 2:
        raise SystemExit(__doc__)
    full = Path(argv[1]) / "World" / "Setup" / "FullDB"
    if not full.is_dir():
        full = Path(argv[1])
    ns = load_data()
    want_npcs, want_items = wanted_names(ns)
    npcs = ids_by_name(full / "creature_template.sql", "creature_template", "Entry", "Name", want_npcs)
    items = ids_by_name(full / "item_template.sql", "item_template", "entry", "name", want_items)
    write(npcs, items)
    print(f"{len(npcs)} of {len(want_npcs)} creature names, {len(items)} of {len(want_items)} item names")


if __name__ == "__main__":
    main(sys.argv)
